#!/usr/bin/env node
/**
 * Generate the pack's cordis.patch.yml from the DSH installation's shipped
 * `standard` preset.
 *
 * The preset row list is versioned deployment data: this script copies the
 * shipped file verbatim and performs one textual edit — the `compaction-basic`
 * row inside the `compaction` group becomes this pack's engine row. Everything
 * else (including `!!js` platform expressions) survives byte for byte, so the
 * generated override always matches the DSH version it was generated against.
 *
 * Usage:
 *   node tools/gen-patch.mjs [path/to/standard.patch.yml] [--out cordis.patch.yml]
 *
 * Resolution order when no path is given: `DSH_WEB_APP_DIR`, the profile's
 * installed `@deepseek-ai/dsh-web-app`, then the same package resolved from this
 * pack's own node_modules link.
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const packDir = resolve(here, '..')

const args = process.argv.slice(2)
const outIndex = args.indexOf('--out')
const outFile = outIndex === -1 ? join(packDir, 'cordis.patch.yml') : resolve(args[outIndex + 1])
const explicit = args.find((arg, index) => !arg.startsWith('--') && index !== outIndex + 1)

/** Candidate shipped preset locations, in resolution order. */
function candidates() {
  const list = []
  if (explicit) list.push(resolve(explicit))
  if (process.env.DSH_WEB_APP_DIR) list.push(join(process.env.DSH_WEB_APP_DIR, 'presets/standard.patch.yml'))
  const profile = process.env.DSH_PROFILE_DIR
  if (profile) list.push(join(profile, 'node_modules/@deepseek-ai/dsh-web-app/presets/standard.patch.yml'))
  try {
    const manifest = createRequire(import.meta.url).resolve('@deepseek-ai/dsh-web-app/package.json')
    list.push(join(dirname(manifest), 'presets/standard.patch.yml'))
  } catch {
    // The pack's dependency link is absent; the other candidates still apply.
  }
  return list
}

const source = candidates().find(path => existsSync(path))
if (source === undefined) {
  console.error(
    'gen-patch: cannot find the shipped standard preset; '
    + 'pass its path explicitly or set DSH_WEB_APP_DIR',
  )
  process.exit(1)
}

const original = readFileSync(source, 'utf8').replace(/\r\n/g, '\n')
const lines = original.split('\n')

const rowIndex = lines.findIndex(line => /^\s*- id: compaction-basic\s*$/.test(line))
if (rowIndex === -1) {
  console.error(`gen-patch: ${source} has no compaction-basic row; the shipped preset changed shape`)
  process.exit(1)
}
const indent = lines[rowIndex].match(/^\s*/)[0]
const nameLine = lines[rowIndex + 1] ?? ''
if (!/name:\s*'@deepseek-ai\/dsh-compaction-basic'/.test(nameLine)) {
  console.error(`gen-patch: unexpected row after compaction-basic in ${source}: ${nameLine}`)
  process.exit(1)
}
lines.splice(
  rowIndex,
  2,
  `${indent}- id: compaction-engine`,
  `${indent}  name: '@dsh-external/dsh-compaction-pack/engine'`,
)

const rootRows = [
  '',
  '# Compaction pack: the tuning service behind the settings card, and the card itself.',
  '# The engine row lives inside the preset override above.',
  '- insert:',
  '    - id: compaction-tuning',
  "      name: '@dsh-external/dsh-compaction-pack/tuning'",
  '',
  '    - id: compaction-pack-ui',
  "      name: '@dsh-external/dsh-compaction-pack'",
  '',
].join('\n')

const banner = [
  '# Generated by tools/gen-patch.mjs from the installed',
  '# dsh-web-app/presets/standard.patch.yml. Regenerate after upgrading DSH so',
  '# the preset override matches the shipped list.',
  '',
].join('\n')

writeFileSync(outFile, `${banner}${lines.join('\n').replace(/\n+$/, '\n')}${rootRows}`, 'utf8')
console.log(`gen-patch: wrote ${outFile}`)
